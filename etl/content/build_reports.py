"""Generate the data-quality reports in docs/ from the curated content, the verified document register and the localization audit.

    python etl/content/build_reports.py [path/to/localization_audit.json]

Every number is computed from the files; nothing is typed by hand.
"""
from __future__ import annotations

import collections
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from schemes_content import CHECK, REFERENCE_NOTE, SCHEMES  # noqa: E402
from services_content import SERVICES  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
DOCS = json.loads((ROOT / "data" / "policy_documents" / "documents.json").read_text(encoding="utf-8"))
ROWS = {r[0]: r for r in json.loads((ROOT / "data" / "content" / "esevai_service_list_2023-04-10.json").read_text(encoding="utf-8"))}
CATS = [("government_order", "Government Orders"), ("policy", "Policy documents"), ("circular", "Circulars"), ("notification", "Notifications"), ("act", "Acts")]


def md_table(head, rows):
    out = ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"]
    out += ["| " + " | ".join(str(c).replace("|", "\\|").replace("\n", " ") for c in r) + " |" for r in rows]
    return "\n".join(out)


def documents_report() -> str:
    by = collections.Counter(d["category"] for d in DOCS)
    ver = collections.Counter(d["category"] for d in DOCS if d["verification_status"] == "official_verified")
    visual = [d for d in DOCS if d["verification_status"] == "official_verified" and d["verification"]["text_chars"] < 200]
    text = [d for d in DOCS if d["verification_status"] == "official_verified" and d["verification"]["text_chars"] >= 200]
    lines = [f"# Tamil Nadu government document research ({CHECK})", "",
             "Generated by `etl/content/build_reports.py` from `data/policy_documents/documents.json` (built by `etl/policy_documents/build_documents.py`).", "",
             "## Method", "",
             "1. Documents were discovered on **official Tamil Nadu listing pages** (not search engines): the Tamil Nadu Government Gazette Extraordinary 2026 list (stationeryprinting.tn.gov.in), "
             "the Rural Development and Panchayat Raj G.O. page (tnrd.tn.gov.in), the Municipal Administration G.O. page (tnurbantree.tn.gov.in), the Tamil Nadu State Judicial Academy circulars list (tnsja.tn.gov.in), "
             "and department sites hosting policy notes / G.O.s (forests.tn.gov.in, tnhb.tn.gov.in, dish.tn.gov.in).",
             "2. Every PDF was **downloaded** and must be a real PDF. A record is `official_verified` only if its extracted text contains the expected identifier/subject words, "
             "or - for scanned PDFs without a text layer - if page 1 was rendered and its title, number and date were **checked by eye** against the record (recorded in `verification_method`).",
             "3. Two candidates were replaced because the official link returned 404 on the research date (G.O. 5 of the RDPR list, which is why G.O. 58 is used instead; and a guessed Act file name, corrected from the listing) and one policy note (Labour) returned 403 and was dropped.",
             "4. Where a check showed the listing description was wrong, the record follows the document: G.O. 105 (2020) is an **Adi Dravidar and Tribal Welfare** order (funeral assistance Rs.2,500 to Rs.5,000), "
             "not a Municipal Administration order; G.O. 64 (2025) is a **Social Welfare and Women Empowerment** order dated 18.06.2025.", "",
             "## Results", "",
             md_table(["Category", "Target", "Found", "Official-verified", "Working PDF"],
                      [[n, 10 if c not in ("government_order", "policy") else "10 (together)", by[c], ver[c], sum(1 for d in DOCS if d["category"] == c and d["pdf_url"])] for c, n in CATS]), "",
             f"* Total: **{len(DOCS)}** documents, **{sum(ver.values())}** official-verified, **{sum(1 for d in DOCS if d['pdf_url'])}** with a downloaded, readable official PDF.",
             f"* Verified by text match on the PDF: {len(text)}; verified by page-1 visual check of a scanned PDF: {len(visual)}.",
             f"* English titles and summaries: {sum(1 for d in DOCS if d['title'] and d['summary_en'])}/{len(DOCS)}. Tamil summaries: {sum(1 for d in DOCS if d['summary_ta'])}/{len(DOCS)} "
             f"(all unreviewed translations written for this project, flagged `summary_ta_reviewed = false`). Official Tamil titles: {sum(1 for d in DOCS if d['title_ta'])}/{len(DOCS)} - none was published for these documents, so none is shown.",
             "", "## Limits and uncertainty", "",
             "* **Circulars** are circulars of the High Court of Madras / Tamil Nadu State Judicial Academy for the district judiciary; they concern citizen matters (victim compensation, maternity leave, bonded labour, tobacco ban, legal aid) indirectly. "
             "Department-issued welfare circulars were not found on a machine-readable official list in this pass.",
             "* **Acts**: each Act is published in an Extraordinary Gazette issue that contains several Acts, so those Acts share one PDF. Publication in the Gazette is recorded as `legal_status`; the **date of coming into force is not confirmed** and `effective_on` is empty. "
             "Act 11 carries the year 2024 in its short title but is numbered Act 11 of 2026 in the Gazette listing - recorded as published.",
             "* `superseded_status` is `unknown` for every document; no document was checked against later amendments.",
             "* The gazette list was read for the 2026 volume only; earlier foundational Acts are not included.", "",
             "## Register", "",
             md_table(["ID", "Category", "Identifier", "Issued", "Department", "Status", "Method", "PDF"],
                      [[d["id"], d["category"], d["identifier"], d["issued"] or "unconfirmed", d["department"], d["verification_status"],
                        ("text match" if d["verification"]["text_chars"] >= 200 else "visual check") if d["verification_status"] == "official_verified" else "-", d["pdf_url"] or d["landing_url"]] for d in DOCS]), ""]
    return "\n".join(lines)


def schemes_report() -> str:
    n = len(SCHEMES)
    elig = sum(1 for s in SCHEMES if s["eligibility"])
    excl = sum(1 for s in SCHEMES if s["exclusions"])
    ben = sum(1 for s in SCHEMES if s["benefits"])
    docs = sum(1 for s in SCHEMES if s["docs"])
    steps = sum(1 for s in SCHEMES if s["steps"] or s["how_note"])
    amt = collections.Counter(b["amount_status"] for s in SCHEMES for b in s["benefits"])
    lvl = collections.Counter(d["level"] for s in SCHEMES for d in s["docs"])
    ev = [s for s in SCHEMES if s["ev"]]
    lines = [f"# Scheme data completeness ({CHECK})", "",
             f"Generated from `etl/content/schemes_content.py`. {REFERENCE_NOTE}", "",
             "## Sources", "",
             "* The project's compiled scheme reference (a PDF supplied with the task) - **not an official source** and says so itself.",
             "* Official pages actually read on the research date: PM-KISAN portal, Commissionerate for Welfare of the Differently Abled (marriage assistance), TN AgriSnet sericulture schemes, Mudhalvar Marundhagam instructions, "
             "and the official **e-Sevai Service List** (document lists for the pension schemes and CMUPT).",
             "* The Commissionerate of Revenue Administration pages (`cra.tn.gov.in/...`) cited in the reference **returned 404** on the research date. Pension amounts (Rs.1,200 / Rs.1,500) come from a search-engine snapshot of that official page (as of March 2024) and are stored as `historical`.",
             "* For Kalaignar Magalir Urimai, CMCHIS, Pudhumai Penn and Innuyir Kappom no official page could be read; the criteria come from news reports and are stored as unverified, with the conflicts shown (for example CMCHIS income limit Rs.1,20,000 vs Rs.72,000; the cover increase to Rs.25 lakh is reported but unconfirmed).", "",
             "## Completeness", "",
             md_table(["Field", f"Schemes with data (of {n})"],
                      [["Eligibility conditions", elig], ["Exclusions", f"{excl} (only where stated)"], ["Benefits", ben], ["Required documents", docs], ["Application procedure", steps],
                       ["Tamil name (all existing records keep their seeded Tamil name)", sum(1 for s in SCHEMES if s["name_ta"])], ["Tamil short description", sum(1 for s in SCHEMES if s["desc_ta"])],
                       ["Fields read on an official page", f"{len(ev)} schemes ({sum(len(s['ev']) for s in ev)} fields)"]]), "",
             "Benefit amounts by confidence: " + ", ".join(f"{k}: {v}" for k, v in sorted(amt.items())) + ".", "",
             "Document levels: " + ", ".join(f"{k}: {v}" for k, v in sorted(lvl.items())) + ". `required` is used only where an official source names the document for that scheme; the rest are `unverified` (compiled), `conditional` or `category_specific`.", "",
             "## What remains unverified", "",
             "Every scheme stays `provisional` (one is `externally_referenced`); none was promoted to `official_verified`. Application windows/deadlines are not stated for any scheme because none was confirmed. "
             "The Tamil text of eligibility, exclusion, step and benefit prose is **not translated**: it is shown in English (marked `lang=\"en\"`) with a notice in Tamil mode; only names, short descriptions and interface text are in Tamil.", "",
             "## Per scheme", "",
             md_table(["Code", "Eligibility", "Benefits", "Documents", "Steps", "Official-page fields"],
                      [[s["code"], len(s["eligibility"]), len(s["benefits"]), len(s["docs"]), len(s["steps"]), ", ".join(s["ev"]) or "-"] for s in SCHEMES]), ""]
    return "\n".join(lines)


def services_report() -> str:
    n = len(SERVICES)
    official = [s for s in SERVICES if s["row"] and any(ROWS[r][7] not in ("", "NA") for r in ([s["row"]] if isinstance(s["row"], str) else s["row"]))]
    listed = [s for s in SERVICES if s["row"]]
    timelines = [s for s in SERVICES if s["row"] and ROWS[(s["row"] if isinstance(s["row"], str) else s["row"][0])][4] not in ("-", "")]
    lines = [f"# Service data completeness ({CHECK})", "",
             "Generated from `etl/content/services_content.py` and `data/content/esevai_service_list_2023-04-10.json` (rows copied from the official list).", "",
             "## Source", "",
             "The **official Tamil Nadu e-Sevai Service List** (`https://www.tnesevai.tn.gov.in/Pages/ServiceList.aspx`, *Last Updated: 10/04/2023*) was downloaded and parsed. It gives, per service, the stipulated timeline, "
             "the fee, the service-centre charge and the document list. It is **more than three years old**, so every fee and timeline is labelled with that date and a note to confirm on the live portal. "
             "Earlier seed values that the list does not support (for example processing times of 3 / 7 / 15 / 30 days and an Rs.100 EC fee) were **removed**.", "",
             "## Completeness", "",
             md_table(["Field", f"Services (of {n})"],
                      [["Present on the official e-Sevai list", len(listed)], ["Document list taken from the official list (`required`)", len(official)],
                       ["Document list compiled (unverified) or absent", n - len(official)], ["Official stipulated timeline", len(timelines)],
                       ["Fee / service charge shown (labelled 2023)", len(listed)], ["No official fee, timeline or document list (shown as not confirmed)", n - len(listed)],
                       ["Tamil name", sum(1 for s in SERVICES if s["name_ta"])], ["Tamil description", sum(1 for s in SERVICES if s["desc_ta"])]]), "",
             "The project reference lists 20 services but numbers 21; all 21 are included.", "",
             "## Per service", "",
             md_table(["Code", "Official row", "Official documents", "Timeline", "Fee"],
                      [[s["code"], (s["row"] if isinstance(s["row"], str) else ",".join(s["row"])) if s["row"] else "-",
                        "yes" if s in official else "no", (ROWS[(s['row'] if isinstance(s['row'], str) else s['row'][0])][4]) if s["row"] and s in timelines else "-",
                        (f"fee {ROWS[(s['row'] if isinstance(s['row'], str) else s['row'][0])][5]} + charge {ROWS[(s['row'] if isinstance(s['row'], str) else s['row'][0])][6]}" if s['row'] and not s['fee_override'] else (s['fee_override'] or 'not listed')) ] for s in SERVICES]), ""]
    return "\n".join(lines)


def localization_report(audit_path: Path | None) -> str:
    lines = [f"# Localization audit ({CHECK})", "",
             "Interface text exists in English and Tamil. Strings live in typed locale modules (`frontend/src/lib/locales/*.ts`): each module declares `ta: Record<keyof typeof en, string>`, "
             "so a missing Tamil entry is a **compile error**. The Tamil is an **unreviewed translation written for this project**; it has not been checked by a professional translator.", "",
             "## Rules", "",
             "* Scheme and service names are always shown in both languages (selected language first, the other in brackets or on a second line).",
             "* Department, category and district names come from the database's `name_ta` columns (`GET /api/v1/public/names`).",
             "* API errors are translated from the HTTP status, never from the server's English text.",
             "* Government-supplied prose without a Tamil version (eligibility lists, application steps, document names, complaint text, assistant answers when the model answers in English) is shown unchanged, marked `lang=\"en\"`, with a visible notice in Tamil mode.",
             "* Monospace text (identifiers, SQL, schema notation) and database values in the technical admin / Architecture views are not translated.",
             "* Official document titles are never translated; no official Tamil title was published for the documents in the catalogue.", ""]
    if audit_path and audit_path.exists():
        r = json.loads(audit_path.read_text(encoding="utf-8"))
        states = sorted({x["state"] for x in r})
        lines += ["## Automated render audit", "",
                  "`frontend/audit/localization.js` renders every route/state in both languages and lists any visible text node, placeholder, aria-label, title, alt or option in the wrong language "
                  "(rules in `frontend/audit/i18n-scan.js`). The same scanner runs in CI as `frontend/e2e/localization.spec.ts` (15 states x 2 languages plus detail pages).", "",
                  f"* States rendered: **{len(states)}** x 2 languages = {len(r)} renders; renders with errors: {sum(1 for x in r if x['error'])}.",
                  f"* Issues found: Tamil **{sum(len(x['issues']) for x in r if x['lang'] == 'ta')}**, English **{sum(len(x['issues']) for x in r if x['lang'] == 'en')}**.",
                  f"* Missing-translation warnings logged by the app: {sum(len(x['missing_keys']) for x in r)}.", "",
                  md_table(["State", "Role", "Tamil issues", "English issues"],
                           [[s, next(x['role'] for x in r if x['state'] == s), sum(len(x['issues']) for x in r if x['state'] == s and x['lang'] == 'ta'),
                             sum(len(x['issues']) for x in r if x['state'] == s and x['lang'] == 'en')] for s in states]), ""]
        remaining = [(x["state"], i) for x in r for i in x["issues"]]
        if remaining:
            lines += ["### Remaining issues", ""] + [f"* {s}: `{i['text'][:100]}` ({i['where']})" for s, i in remaining[:40]] + [""]
    lines += ["## Known limitations", "",
              "* Long-form government text (see rules above) is English-only in Tamil mode.",
              "* Policy-document summaries in Tamil are unreviewed translations, flagged in the interface.",
              "* The assistant answers in the language the model produces; the interface labels the answer language when it differs from the selected one.",
              "* The automated audit cannot judge translation quality; a Tamil-speaking reviewer should check the locale files before public release."]
    return "\n".join(lines)


def main() -> None:
    audit = Path(sys.argv[1]) if len(sys.argv) > 1 else None
    (ROOT / "docs" / "tamilnadu-government-document-research.md").write_text(documents_report(), encoding="utf-8")
    (ROOT / "docs" / "scheme-data-completeness.md").write_text(schemes_report(), encoding="utf-8")
    (ROOT / "docs" / "service-data-completeness.md").write_text(services_report(), encoding="utf-8")
    (ROOT / "docs" / "localization-audit.md").write_text(localization_report(audit), encoding="utf-8")
    print("reports written")


if __name__ == "__main__":
    main()
