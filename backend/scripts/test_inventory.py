"""Generate docs/audit/test_inventory.md from ACTUAL test results.

    pytest tests --junitxml=pytest-report.xml            (with TEST_ADMIN_DSN / TEST_POSTGIS / TEST_NEO4J_URI set)
    npx playwright test                                   (writes frontend/e2e/results.json)
    python -m scripts.test_inventory pytest-report.xml ../frontend/e2e/results.json > ../docs/audit/test_inventory.md

Counts, outcomes and timings come straight from the reports; the classification and dependency columns come
from the file's location and markers. Nothing is hand-edited.
"""
from __future__ import annotations

import json
import sys
import xml.etree.ElementTree as ET
from collections import defaultdict
from pathlib import Path

NOTES = {
    "tests/unit": ("unit", "none"),
    "test_sql_schema_conformance": ("integration (schema)", "PostgreSQL"),
    "test_postgis_spatial": ("spatial (PostGIS)", "PostgreSQL + real PostGIS (TEST_POSTGIS=1)"),
    "test_knowledge_graph": ("integration (graph)", "PostgreSQL; Neo4j-backed tests need TEST_NEO4J_URI"),
    "test_ingestion": ("integration (ETL)", "PostgreSQL; HTTP is mocked"),
    "test_embeddings": ("integration (AI)", "PostgreSQL + pgvector; providers are faked / HTTP mocked"),
    "test_rag_assistant": ("integration (AI)", "PostgreSQL + pgvector; LLM and embedder are fakes"),
}


def classify(file: str) -> tuple[str, str]:
    for key, v in NOTES.items():
        if key in file:
            return v
    return ("integration (API)", "PostgreSQL (disposable)") if "tests/integration" in file else ("unit", "none")


def pytest_rows(path: Path) -> dict[str, dict]:
    rows: dict[str, dict] = defaultdict(lambda: {"passed": 0, "failed": 0, "skipped": 0, "time": 0.0})
    for tc in ET.parse(path).getroot().iter("testcase"):
        key = "backend/" + tc.get("classname", "?").replace(".", "/") + ".py"
        r = rows[key]
        r["time"] += float(tc.get("time", 0))
        if tc.find("failure") is not None or tc.find("error") is not None:
            r["failed"] += 1
        elif tc.find("skipped") is not None:
            r["skipped"] += 1
        else:
            r["passed"] += 1
    return rows


def e2e_rows(path: Path) -> dict[str, dict]:
    rows: dict[str, dict] = defaultdict(lambda: {"passed": 0, "failed": 0, "skipped": 0, "time": 0.0})

    def walk(suite):
        for sp in suite.get("specs", []):
            for t in sp["tests"]:
                for res in t["results"]:
                    r = rows["frontend/e2e/" + sp["file"].replace("\\", "/").split("/")[-1]]
                    r["time"] += res.get("duration", 0) / 1000
                    r[{"passed": "passed", "skipped": "skipped"}.get(res["status"], "failed")] += 1
        for c in suite.get("suites", []):
            walk(c)

    for s in json.loads(path.read_text(encoding="utf-8"))["suites"]:
        walk(s)
    return rows


def main() -> None:
    py = pytest_rows(Path(sys.argv[1]))
    e2e = e2e_rows(Path(sys.argv[2])) if len(sys.argv) > 2 else {}
    print("# Test inventory\n")
    print("Generated by `python -m scripts.test_inventory` from the JUnit XML and Playwright JSON of the last run. "
          "Outcomes are observed results, not intentions.\n")
    total = {"passed": 0, "failed": 0, "skipped": 0}
    print("| File | Kind | Needs | Passed | Failed | Skipped | Time (s) |\n|---|---|---|---|---|---|---|")
    for file, r in sorted(py.items()):
        kind, needs = classify(file)
        print(f"| `{file}` | {kind} | {needs} | {r['passed']} | {r['failed']} | {r['skipped']} | {r['time']:.1f} |")
        for k in total:
            total[k] += r[k]
    for file, r in sorted(e2e.items()):
        kind = "E2E (accessibility)" if "accessibility" in file else "E2E (browser)"
        print(f"| `{file}` | {kind} | FastAPI + PostgreSQL + production Next build + Chromium | {r['passed']} | {r['failed']} | {r['skipped']} | {r['time']:.1f} |")
        for k in total:
            total[k] += r[k]
    print(f"\n**Total: {total['passed']} passed, {total['failed']} failed, {total['skipped']} skipped.**\n")
    print("Environment-dependent tests are skipped (never silently passed) when their infrastructure is missing: "
          "`postgis` marker needs `TEST_POSTGIS=1`; Neo4j tests need `TEST_NEO4J_URI`; DB tests need `TEST_ADMIN_DSN`.")


if __name__ == "__main__":
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")  # type: ignore[union-attr]
    main()
