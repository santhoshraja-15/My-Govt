"""Generate docs/audit/route_test_inventory.md from the live FastAPI route table.

    python -m scripts.route_inventory > ../docs/audit/route_test_inventory.md

For every route: methods, path, authentication / role requirement (read from the dependency graph), and the
test files that exercise that path (a path counts as covered when a test file contains its literal static
segments, e.g. `/admin/overview`, or `/complaints/` ... `/status` for parameterised paths). A reference proves
the path appears in a test, not that every branch of it is covered - read the tests for that.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

from fastapi.routing import APIRoute

from app.main import app
from app.security import dependencies as deps

ROOT = Path(__file__).resolve().parents[2]
TEST_DIRS = [ROOT / "backend" / "tests", ROOT / "frontend" / "e2e"]


def flatten(routes, prefix: str = ""):
    """Yield (full_path, APIRoute), descending into included routers (FastAPI nests them)."""
    for r in routes:
        if isinstance(r, APIRoute):
            yield prefix + r.path, r
        elif hasattr(r, "original_router"):
            ctx = getattr(r, "include_context", None)
            yield from flatten(r.original_router.routes, prefix + (getattr(ctx, "prefix", "") or ""))
        elif hasattr(r, "routes"):
            yield from flatten(r.routes, prefix)


def auth_of(route: APIRoute) -> str:
    out = "public"
    for d in route.dependant.dependencies:
        call = d.call
        if call is deps.get_current_user:
            out = "any signed-in user"
        elif call is deps.get_current_user_optional:
            out = "optional (signed-in user changes behaviour)" if out == "public" else out
        elif getattr(call, "__qualname__", "").startswith("require_role"):
            closure = getattr(call, "__closure__", None) or ()
            roles = next((c.cell_contents for c in closure if isinstance(c.cell_contents, list)), [])
            out = "roles: " + ", ".join(roles)
    return out


def static_parts(path: str) -> list[str]:
    parts = [p for p in re.split(r"\{[^}]+\}", path) if p.strip("/")]
    return [p.rstrip("/") if p.endswith("/") and len(p) > 1 else p for p in parts]


def referenced_by(path: str, files: dict[Path, str]) -> list[str]:
    parts = static_parts(path)
    hits = []
    for f, text in files.items():
        if all(p in text for p in parts):
            hits.append(f.name)
    return sorted(set(hits))


def main() -> None:
    files = {f: f.read_text(encoding="utf-8", errors="ignore") for d in TEST_DIRS for f in d.rglob("*")
             if f.suffix in (".py", ".ts") and "node_modules" not in f.parts}
    rows = []
    for full, r in flatten(app.routes):
        if full.startswith(("/api/v1", "/health")):
            rows.append((full, ",".join(sorted(m for m in r.methods if m not in ("HEAD", "OPTIONS"))), auth_of(r),
                         referenced_by(full.replace("/api/v1", ""), files)))
    rows.sort()
    covered = sum(1 for *_, t in rows if t)
    print("# Route-to-test inventory\n")
    print("Generated by `python -m scripts.route_inventory` from the live route table. "
          "'Referenced by' means a test file contains the path's static segments.\n")
    print(f"**{covered} of {len(rows)} routes are referenced by at least one test.**\n")
    print("| Method | Path | Access | Referenced by |\n|---|---|---|---|")
    for path, methods, auth, tests in rows:
        print(f"| {methods} | `{path}` | {auth} | {', '.join(tests) if tests else '**none**'} |")


if __name__ == "__main__":
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")  # type: ignore[union-attr]
    main()
